import pathlib, re
txt = pathlib.Path(r"E:\il2cpp\src\il2cppc\Emit\MethodMap.Decimal.cs").read_text(encoding='utf-8')
ics = re.findall(r'"(icall_decimal_[^"]+)"', txt)
pref = re.findall(r'il2cpp::runtime::(icall_decimal_\w+)', txt)
all_map = sorted(set(ics + pref))
print('MAP unique count', len(all_map))
for x in all_map: print('MAP', x)
def hdr_names(path):
    t = pathlib.Path(path).read_text(encoding='utf-8', errors='ignore')
    return sorted(set(re.findall(r'^\s*(?:int32_t|int64_t|uint32_t|uint64_t|double|float|void|bool|Il2CppString\*)\s+(icall_decimal_\w+)\s*\(', t, flags=re.MULTILINE)))
hdr = hdr_names(r"E:\il2cpp\src\runtime\include\internal\decimal.h")
print('HDR count', len(hdr))
for x in hdr: print('HDR', x)
def def_names(path):
    t = pathlib.Path(path).read_text(encoding='utf-8', errors='ignore')
    return sorted(set(re.findall(r'^\s*(?:int32_t|int64_t|uint32_t|uint64_t|double|float|void|bool|Il2CppString\*)\s+(icall_decimal_\w+)\s*\(', t, flags=re.MULTILINE)))
defs = def_names(r"E:\il2cpp\src\runtime\src\decimal.cpp")
print('DEF decimal.cpp count', len(defs))
for x in defs: print('DEF', x)
txt2 = pathlib.Path(r"E:\il2cpp\src\runtime\include\internal\decimal_format.h").read_text(encoding='utf-8')
print('decimal_format.h icalls:', re.findall(r'icall_decimal_\w+', txt2))
txt3 = pathlib.Path(r"E:\il2cpp\src\runtime\src\decimal_format.cpp").read_text(encoding='utf-8')
print('decimal_format.cpp icalls:', sorted(set(re.findall(r'icall_decimal_\w+', txt3))))
