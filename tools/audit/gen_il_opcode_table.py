"""Generate the IL operand-size table used by WinFormsPinvokeGraph.

The table is derived from the CLR's own master opcode definition
(reference/coreclr/src/coreclr/inc/opcode.def), so a mis-sized operand can
never silently desynchronise the scanner: every opcode's operand width comes
from the ECMA-335 operand-kind column rather than from a hand-maintained list.

usage: python tools/audit/gen_il_opcode_table.py \
           reference/corecore/src/coreclr/inc/opcode.def \
           tools/audit/WinFormsPinvokeGraph/IlOpcodeTable.cs
"""

import io
import re
import sys

OPDEF = re.compile(
    r'OPDEF\(\s*CEE_(?P<name>[A-Za-z0-9_]+)\s*,\s*"[^"]*"\s*,\s*[^,]+\s*,\s*[^,]+\s*,\s*'
    r'(?P<kind>\w+)\s*,\s*[^,]+\s*,\s*(?P<len>\d+)\s*,\s*0x(?P<b1>[0-9A-Fa-f]{2})\s*,\s*0x(?P<b2>[0-9A-Fa-f]{2})'
)

# ECMA-335 III.1.9 operand types -> operand byte width. -1 marks the
# switch instruction (variable length, handled by the scanner); -2 marks an
# operand kind this generator does not expect.
WIDTH = {
    'InlineNone': 0,
    'ShortInlineVar': 1,
    'InlineVar': 2,
    'ShortInlineI': 1,
    'InlineI': 4,
    'InlineI8': 8,
    'ShortInlineR': 4,
    'InlineR': 8,
    'ShortInlineBrTarget': 1,
    'InlineBrTarget': 4,
    'InlineMethod': 4,
    'InlineSig': 4,
    'InlineField': 4,
    'InlineType': 4,
    'InlineString': 4,
    'InlineTok': 4,
    'InlineSwitch': -1,
}

# Operand kinds that carry a metadata token the call graph resolves.
TOKEN_KINDS = {'InlineMethod', 'InlineSig', 'InlineTok'}

# The opcode byte that makes the instruction a CALL EDGE (call / callvirt /
# newobj / jmp plus the ldftn forms that hand a method address to a callback
# registration). Everything else only has to be skipped correctly.
CALL_OPCODES = {'CEE_CALL', 'CEE_CALLVIRT', 'CEE_NEWOBJ', 'CEE_JMP', 'CEE_LDFTN', 'CEE_LDVIRTFTN'}

def main():
    def_path, out_path = sys.argv[1], sys.argv[2]
    single = [0] * 256
    prefix = [0] * 256
    calls_single = [False] * 256
    calls_prefix = [False] * 256
    seen = 0

    for line in io.open(def_path, encoding='utf-8', errors='replace'):
        m = OPDEF.search(line)
        if not m:
            continue
        kind = m.group('kind')
        if kind not in WIDTH:
            raise SystemExit('unknown operand kind %s on %s' % (kind, m.group('name')))
        width = WIDTH[kind]
        b1 = int(m.group('b1'), 16)
        b2 = int(m.group('b2'), 16)
        is_call = ('CEE_' + m.group('name')) in CALL_OPCODES
        if b1 == 0xFF:
            single[b2] = width
            calls_single[b2] = is_call
        elif b1 == 0xFE:
            prefix[b2] = width
            calls_prefix[b2] = is_call
        else:
            raise SystemExit('unexpected prefix 0x%02X on %s' % (b1, m.group('name')))
        seen += 1

    sb = io.StringIO()
    sb.write('// <auto-generated>\n')
    sb.write('// Generated by tools/audit/gen_il_opcode_table.py from\n')
    sb.write('// reference/coreclr/src/coreclr/inc/opcode.def (the CLR master opcode table).\n')
    sb.write('// Do not edit by hand: rerun the generator.\n')
    sb.write('// </auto-generated>\n')
    sb.write('namespace WinFormsPinvokeGraph;\n\n')
    sb.write('// IL operand widths: 0 = no operand, -1 = InlineSwitch (variable, scanned\n')
    sb.write('// inline). An opcode absent from the CLR table keeps 0 here; the scanner\n')
    sb.write('// never sees such a byte in a well-formed body, and a bad table would show\n')
    sb.write('// up as a fatal decodeFailure count instead of a silent misparse.\n')
    sb.write('internal static class IlOpcodeTable\n{\n')

    def emit_arr(name, values, typ='sbyte'):
        sb.write('    public static readonly %s[] %s =\n    {\n' % (typ, name))
        for i in range(0, 256, 8):
            chunk = values[i:i + 8]
            sb.write('        ' + ', '.join(str(v) for v in chunk) + ',\n')
        sb.write('    };\n\n')

    emit_arr('Size1', single)
    emit_arr('SizeFe', prefix)
    emit_arr('Call1', ['true' if v else 'false' for v in calls_single], 'bool')
    emit_arr('CallFe', ['true' if v else 'false' for v in calls_prefix], 'bool')
    sb.write('}\n')

    io.open(out_path, 'w', encoding='utf-8', newline='\n').write(sb.getvalue())
    print('opcodes=%d single=%d prefix=%d' % (seen, sum(1 for v in single if v != 0), sum(1 for v in prefix if v != 0)))


if __name__ == '__main__':
    main()
