using System;
using System.Linq;

//------------------------------------------------------------------------------
// loud-p0-04-int -- P0-04: GroupBy with NON-int32 integer KEY families.
//
// The runtime bucket key is an int32 slot (linq_map.h). A narrow key selector
// (`x => (byte)x`) returns its value in a register whose upper bits the C++
// return type does not define, while the callback ABI reads int32_t -- so the
// runtime must NARROW the result back to the declared TKey width
// (il2cpp_linq_group_by_full_key + NarrowKey). Without that narrowing the
// buckets split (byte 44 vs 300), i.e. a WRONG grouping, not a display bug.
//
// Every row below is a case where the UNNARROWED value differs from the
// declared-type value, so a regression immediately shows as extra buckets.
//
// NOTE (unchanged pre-existing gap): the narrow TKey ToString surfaces
// (SByte/Int16/UInt16_ToString) are NOT generated by codegen -- `g.Key.ToString()`
// for sbyte/short/ushort fails to compile with
//   'System_SByte_ToString_...' was not declared in this scope
// (byte/char/bool are fine). Hence the explicit (int)/(long) casts below.
// That gap is tracked in docs/audit/b4-gaps.md together with every other
// deliberately-rejected GroupBy shape (long/ulong/decimal/DateTime/Guid keys,
// non-int32 source arrays). All of those are TRANSPILE-TIME LOUD, never silent.
//
// net48 oracle (first-appearance order):
//   [gb_byte]  key=44 n=3                       (44,300,44 -> one bucket)
//   [gb_sbyte] key=-1 n=3                       (-1,255,-1 -> one bucket)
//   [gb_short] key=-1 n=3                       (-1,65535,-1 -> one bucket)
//   [gb_ushort] key=65535 n=3                   (65535,-1,65535 -> one bucket)
//   [gb_char]  key=4464 n=3                     (70000,4464,4464 -> one bucket)
//   [gb_uint]  key=4294967295 n=2 / key=7 n=1
//   [gb_bool]  key=True n=2 / key=False n=1
//   [gb_int]   key=1 n=3 / key=0 n=1            (int control)
//------------------------------------------------------------------------------
namespace Cases
{
    public static class LoudP004Int
    {
        public static void Main()
        {
            // byte: 300 narrows to 44, so all three land in the same bucket.
            foreach (var g in new[] { 44, 300, 44 }.GroupBy(x => (byte)x))
                Console.WriteLine("[gb_byte] key=" + (int)g.Key + " n=" + g.Count());

            // sbyte: 255 narrows to -1.
            foreach (var g in new[] { -1, 255, -1 }.GroupBy(x => (sbyte)x))
                Console.WriteLine("[gb_sbyte] key=" + (int)g.Key + " n=" + g.Count());

            // short: 65535 narrows to -1.
            foreach (var g in new[] { -1, 65535, -1 }.GroupBy(x => (short)x))
                Console.WriteLine("[gb_short] key=" + (int)g.Key + " n=" + g.Count());

            // ushort: -1 narrows to 65535.
            foreach (var g in new[] { 65535, -1, 65535 }.GroupBy(x => (ushort)x))
                Console.WriteLine("[gb_ushort] key=" + (int)g.Key + " n=" + g.Count());

            // char: 70000 narrows to 4464.
            foreach (var g in new[] { 70000, 4464, 4464 }.GroupBy(x => (char)x))
                Console.WriteLine("[gb_char] key=" + (int)g.Key + " n=" + g.Count());

            // uint: the int32 slot keeps the bit pattern (equality only). The
            // SOURCE stays int32[] (a non-int32 source family is out of scope);
            // -1 projects to uint.MaxValue.
            foreach (var g in new[] { -1, -1, 7 }.GroupBy(x => (uint)x))
                Console.WriteLine("[gb_uint] key=" + (long)g.Key + " n=" + g.Count());

            // bool key over an int32 source (a bool[] SOURCE is out of scope).
            foreach (var g in new[] { 1, 1, 0 }.GroupBy(x => x != 0))
                Console.WriteLine("[gb_bool] key=" + g.Key + " n=" + g.Count());

            // int control (identity key family).
            foreach (var g in new[] { 1, 1, 2, 3 }.GroupBy(x => x % 2))
                Console.WriteLine("[gb_int] key=" + g.Key + " n=" + g.Count());
        }
    }
}
