//------------------------------------------------------------------------------
// IDropTarget dispatch forwarding (stage 16 -- the OLE drag-drop forwarding
// layer, WINDOWS only). The managed dispatch of DragEnter/DragOver/Drop needs
// WinForms domain types (DragEventArgs + a typed IDataObject RCW) that are NOT
// COM-runtime self-contained, so stage 16 registers a per-CCW NATIVE dispatch
// callback the view methods forward the raw OLE arguments to. The forwarding
// keeps the effect/HRESULT bidirectional propagation; the DragEventArgs /
// typed-RCW construction happens later in managed code (the future WinForms
// layer binds a delegate thunk here).
//------------------------------------------------------------------------------

// Register the native dispatch callback 'fn' for the CCW 'ccw' (the identity
// IUnknown pointer icall_com_ccw_create returns -- the register_connection_point
// per-CCW registration precedent). The CCW's IDropTarget view methods decode
// the raw OLE arguments and forward them to the callback:
//
//   int32_t (*)(int32_t method, intptr_t pDataObj, uint32_t grfKeyState,
//               int32_t x, int32_t y, uint32_t* pdwEffect)
//
//   method        -- kComDropMethod* (0=DragEnter, 1=DragOver, 2=Drop,
//                    3=DragLeave)
//   pDataObj      -- the by-value IDataObject* (intptr carrier); DragOver/
//                    DragLeave have no data object (0)
//   grfKeyState   -- the OLE keyboard modifier bits (DWORD, forwarded verbatim)
//   x, y          -- the POINTL members (decoded from the by-value POINTL:
//                    x = low 32 bits, y = high 32 bits -- the stage-15
//                    `const void* pt` declaration was a wrong by-value POINTL
//                    shape: x64 8-byte POINTL occupies one register slot but
//                    read as a pointer is UB; stage 16 carries it as an intptr
//                    and decodes)
//   pdwEffect     -- the OLE effect in/out pointer: on entry carries the
//                    allowed-effect mask, the callback updates *pdwEffect
//                    in place (the caller observes the callback's write)
//   return        -- the callback's HRESULT, returned by the view method
//                    (forwarded, never masked)
//
// Forwarding semantics: DragEnter/DragOver/Drop return the callback's HRESULT
// and propagate the callback's *pdwEffect write-back; DragLeave keeps the
// stage-15 S_OK contract (not forwarded -- a callback could return failure and
// change the locked notification semantics; kComDropMethodDragLeave is
// reserved for a future extension). fn == 0 clears the dispatch -> the
// stage-15 surface is restored (DragLeave S_OK / the rest E_NOTIMPL).
// ccw == 0 -> ArgumentNullException (precedes the platform gate, all platforms).
// Windows: full implementation. Non-Windows: E_NOTIMPL (the POSIX stub).
int32_t icall_com_ccw_register_drop_dispatch(intptr_t ccw, intptr_t fn);

//------------------------------------------------------------------------------
// Managed drop dispatch (stage 17 batch 4 -- EVERY platform). The full
// managed drag-drop dispatch -- the CCW->OnDragEnter bridge -- as the additive
// completion of register_drop_dispatch (stage 16): the Windows IDropTarget
// view methods (CcwDropDispatchImpl) call the pump below AFTER the POINTL
// decode, and the managed mode takes priority over the stage-16 native
// forwarding callback (the register_drop_dispatch callback stays as the
// documented lower-level option). The bridge core is pure memory + typeinfo +
// il2cpp_interface_dispatch (no ole32 dependency -- the stage-17 typed-view
// every-platform precedent); the CCW state it reads (dropManaged/dropIface/
// dropSlots/dropEffectOffset) lives OUTSIDE the Windows gate.
//------------------------------------------------------------------------------

// Declare the managed drop dispatch on the CCW 'ccw' (the identity IUnknown
// pointer icall_com_ccw_create returns -- the per-CCW registration precedent).
// 'ifaceClass' is the transpiled IDropTarget descriptor and 'argsClass' the
// DragEventArgs descriptor (both intptr carriers -- com.cpp cannot reference
// generated symbols). Registration resolves the interface's typeinfo
// (il2cpp_typeinfo_lookup by name) and caches, per kComDropMethod* (0=DragEnter
// 1=DragOver 2=Drop 3=DragLeave), the MANAGED interface slot of the method
// whose NAME matches kDropMethodNames (the typeinfo virtualSlot lookup -- the
// transpiler sorts interface slots ALPHABETICALLY: OnDragDrop=0/OnDragEnter=1/
// OnDragLeave=2/OnDragOver=3, so only the name is a stable bridge to the OLE
// declarative order). The registration SELF-VALIDATES the pairing:
//   * ifaceClass->instanceSize must be 0 (a real interface descriptor, not a
//     concrete class) else E_INVALIDARG;
//   * every drop method the interface declares must match the "v(r:<args>)"
//     shape -- a void method with exactly one reference parameter whose type
//     name equals argsClass->name (a mismatched args class is E_INVALIDARG; an
//     interface that simply does not declare a method leaves its slot at -1,
//     the dispatch answers E_NOTIMPL);
//   * argsClass must have reflected typeinfo AND a ".ctor" (else
//     E_INVALIDARG);
//   * the argsClass "Effect" FIELD offset is resolved and cached (a class
//     without an Effect field caches -1 -> no write-back).
// ccw/ifaceClass/argsClass == 0 -> ArgumentNullException. Re-registering
// replaces the state (validate-then-write: a rejected registration leaves the
// prior registration intact); there is no clear -- an unregistered CCW is the
// fallback (pump -> E_NOTIMPL). Implemented on EVERY platform.
int32_t icall_com_ccw_register_drop_dispatch_managed(intptr_t ccw, intptr_t ifaceClass, intptr_t argsClass);

// Drive the managed drop dispatch -- the shared bridge core the Windows
// IDropTarget view methods call after the POINTL decode (x = low 32 bits of
// the by-value POINTL carrier, y = high 32 bits), and the direct entry a
// caller or test uses with already-decoded x/y. 'method' is kComDropMethod*
// (0=DragEnter 1=DragOver 2=Drop 3=DragLeave -- the pump ALSO supports 3, the
// programmatic OnDragLeave the view never uses), 'pDataObj' the by-value
// IDataObject* (0 = none -- DragOver/DragLeave), 'grfKeyState' the OLE
// modifier bits (DROPPED -- the fixture DragEventArgs has no KeyState field),
// 'x'/'y' the POINTL members and 'pdwEffect' the effect in/out pointer (in =
// the allowed mask the ctor seeds ev->Effect with; out = ev->Effect written
// back through the cached Effect field offset). Pipeline:
//   data = (pDataObj != 0) ? icall_com_wrap_data_object(pDataObj, 0) : 0
//   ev   = il2cpp_object_construct(argsClass, data, x, y, *pdwEffect)
//   il2cpp_interface_dispatch(managed, dropIface, dropSlots[method])(managed, ev)
//   *pdwEffect = ev->Effect  (only when pdwEffect != 0 and the offset is >= 0)
// The dispatch is guarded by il2cpp_is_instance (a non-implementer returns
// E_NOTIMPL -- never an interface_dispatch abort). Unregistered (dropManaged
// == 0) / an undeclared method (slot -1) / a null GCHandle target / a
// construct failure -> E_NOTIMPL. ccw == 0 -> ArgumentNullException; method
// outside 0..3 -> ArgumentOutOfRangeException. Implemented on EVERY platform.
int32_t icall_com_ccw_drop_dispatch_managed(intptr_t ccw, int32_t method, intptr_t pDataObj,
                                            uint32_t grfKeyState, int32_t x, int32_t y, uint32_t* pdwEffect);

// Register the IDispatch::Invoke -> managed-method dispatch on a CCW (stage
// 18 -- the ActiveX / WebBrowser automation backing). GetIDsOfNames already
// resolves names to dispIds (phase 2); Invoke validates the DISPPARAMS
// (phase 7) and then, when THIS dispatch is registered, resolves the member
// NAME to the managed interface slot (the interface's typeinfo) and calls
// through il2cpp_interface_dispatch. The managed return type comes from the
// typeinfo signature: 'i' -> the int32 is written as VT_I4, 'v' -> VT_EMPTY;
// the interface's int-typed methods are the supported automation shape
// (int params arrive as VT_I4 in rgvarg[0..cArgs), positional order).
// ifaceClass must be an interface descriptor (instanceSize == 0) with
// reflected typeinfo; a rejected registration leaves the prior state intact.
// ccw == 0 / ifaceClass == 0 -> ArgumentNullException. EVERY platform.
int32_t icall_com_ccw_register_invoke_dispatch(intptr_t ccw, intptr_t ifaceClass);

//------------------------------------------------------------------------------
// IDataObject view (stage 17 batch 2 -- the typed-RCW foundation; the WinForms
// DragEventArgs.Data dependency). The CCW exposes a 12-slot IDataObject view
// (IUnknown + the 9 canonical oleidl.h methods) at &ccw->dataObjectVtbl whose
// native slots bridge to the MANAGED interface by NAME: the managed wiring
// layer registers a transpiled interface descriptor (its Il2CppClass*) for the
// CCW via icall_com_ccw_register_interface_view, and the view methods dispatch
// into the CCW's wrapped managed object through il2cpp_interface_dispatch.
// The name-resolution exists because the transpiler sorts interface slots
// ALPHABETICALLY (batch-2 fixture: GetData=0/QueryGetData=1/SetData=2) while
// the OLE vtable follows the DECLARATIVE oleidl.h order (GetData/GetDataHere/
// QueryGetData/GetCanonicalFormatEtc/SetData/EnumFormatEtc/DAdvise/DUnadvise/
// DEnumFormatEtc -- slots 3..11) -- the two orders differ, so the bridge maps
// each native slot to the interface method NAME and resolves the interface's
// vtable position through its typeinfo (the virtualSlot lookup).
//------------------------------------------------------------------------------

// IDataObject method slots (slots are interface-relative after the IUnknown
// base: 0=QI, 1=AddRef, 2=Release -- canonical oleidl.h order).
constexpr int32_t kComDataObjectSlotGetData             = 3; // (FORMATETC, STGMEDIUM) -- void
constexpr int32_t kComDataObjectSlotGetDataHere         = 4; // (FORMATETC, STGMEDIUM) -- void
constexpr int32_t kComDataObjectSlotQueryGetData        = 5; // (FORMATETC) -- int HRESULT
constexpr int32_t kComDataObjectSlotGetCanonicalFormatEtc = 6; // (FORMATETC, FORMATETC) -- int HRESULT
constexpr int32_t kComDataObjectSlotSetData             = 7; // (FORMATETC, STGMEDIUM, bool) -- void
constexpr int32_t kComDataObjectSlotEnumFormatEtc       = 8; // (DATADIR, IEnumFORMATETC) -- int HRESULT
constexpr int32_t kComDataObjectSlotDAdvise             = 9; // (FORMATETC, ADVF, IAdviseSink, DWORD) -- int HRESULT
constexpr int32_t kComDataObjectSlotDUnadvise           = 10; // (DWORD) -- void
constexpr int32_t kComDataObjectSlotDEnumFormatEtc      = 11; // (DWORD) -- int HRESULT

// Declare 'ifaceClass' (an Il2CppClass* carrier -- a transpiled interface
// descriptor, e.g. the batch-2 fixture's IDataObject) as the CCW 'ccw' (the
// identity IUnknown pointer icall_com_ccw_create returns) typed interface view
// behind IID_IDataObject (the register_connection_point / register_drop_dispatch
// per-CCW registration precedent). Registration resolves the interface's
// typeinfo (il2cpp_typeinfo_lookup by the descriptor's name) and caches, per
// native IDataObject slot, the MANAGED interface slot of the method whose NAME
// matches the oleidl method name (kDataObjectMethodNames -- the virtualSlot
// lookup); a native method the interface does not declare stays at -1 and the
// view method answers E_NOTIMPL (the IOleObject minimal-surface precedent).
// The view's methods dispatch into the CCW's wrapped managed object by
// il2cpp_interface_dispatch: void methods return S_OK, int-returning methods
// propagate their int32 result as the HRESULT carrier (the batch-2 fixture
// subset v(i,i)/i(i)).
//
// The CCW's QueryInterface hands the view out ONLY when the view is registered
// AND il2cpp_is_instance confirms the wrapped object implements the registered
// interface (dispatching to a non-implementer would hit the interface-dispatch
// abort -- a programming-error path); otherwise E_NOINTERFACE.
//
// ccw == 0 / iid == nullptr / ifaceClass == 0 -> ArgumentNullException (the
// null checks precede the platform gate, all platforms); a non-IDataObject IID
// -> E_INVALIDARG (the typed view registry currently serves the IDataObject
// IID only). Implemented on EVERY platform (pure memory + typeinfo + dispatch
// -- no ole32 dependency, the stage-10 every-platform precedent).
int32_t icall_com_ccw_register_interface_view(intptr_t ccw, const uint8_t iid[16], intptr_t ifaceClass);

