// Basic vtable-slot invocation (phase-1 "basic method call"). Calls the
// interface method at vtable slot 'slot' on 'iface' (intptr carrier) with up
// to four intptr-sized arguments (a0..a3), returning the method's intptr
// result (HRESULT-returning methods carry their HRESULT in the low 32 bits --
// the M-stage intptr result kind). The slot layout is the COM vtable
// contract: slot 0 = QueryInterface, 1 = AddRef, 2 = Release, 3+ interface
// methods. Slot < 0 or > 127 -> ArgumentOutOfRangeException (bounds defense);
// a CCW (whose vtable has exactly the 7 IUnknown+IDispatch slots -- phase 2)
// additionally rejects any slot past 6 -- an OOB read guard on the CCW
// vtable; iface == 0 -> ArgumentNullException. Argument COUNT: phase 1 fixes
// the 4-arg shape (methods with fewer args pass ignored trailing zeros; the
// transpiler's arg-cast list maps int32/intptr/string slots onto a0..a3). The
// IDispatch methods (GetTypeInfoCount/GetTypeInfo/GetIDsOfNames/Invoke) need
// 1-5 arguments and are reached through the dedicated idispatch icalls below
// instead of this 4-arg shape.
