//------------------------------------------------------------------------------
// il2cpp_com.h -- COM interop runtime (user iron rule #17: CCW/RCW behavior
// identical to .NET Framework). Windows is the GUARANTEED platform; every
// other platform compiles a documented stub (explicit error / 0 / no crash,
// never silent -- the platform-limitation contract, see com.cpp).
//
// PHASE 1-2 SCOPE (batches b23 + b26com2): minimal RCW + basic Marshal COM
// surface + a CCW whose vtable carries IUnknown (QI/AddRef/Release) AND
// IDispatch (GetTypeInfoCount/GetTypeInfo/GetIDsOfNames/Invoke -- phase 2,
// the ActiveX/automation late-binding surface: a native host can QI a CCW for
// IDispatch, resolve method names to dispIds and invoke them; the RCW
// direction exposes the same two calls for driving native automation
// objects). The surface intentionally mirrors the net48 Marshal COM members
// that the icall inventory (icall-inventory-net48.md section 4) listed as
// "23 COM members LOUD-rejected" -- the MethodMap COM domain wiring report
// (the "23 LOUD flips") maps those members to the icalls declared here (see
// the batch report for the per-member mapping).
//
// MODEL (reference semantics, .NET Framework 4.8):
//   * An RCW is a managed object (Il2CppObject*) whose payload holds the
//     native IUnknown* it wraps (the managed object keeps the COM reference
//     alive for its lifetime). The RCW class descriptor is a runtime-only
//     descriptor (il2cpp_com_rcw_class, marshalext.cpp's g_int32ArrayClass
//     precedent -- a static descriptor never emitted by the transpiler).
//   * The low-level interface-pointer operations (QueryInterface / AddRef /
//     Release / vtable-slot invocation) take/return the native pointer as an
//     intptr_t carrier (the M-stage IntPtr model, MethodMap.IntPtr.cs "ptr"
//     result kind) -- Marshal.QueryInterface/AddRef/Release on net48 operate
//     on IntPtr pUnk exactly this way.
//   * Marshal.GetActiveObject / Marshal.CreateObject (CoCreateInstance via
//     ProgID or CLSID) return the RCW managed object; Marshal.GetTypeFromProgID
//     resolves ProgID -> CLSID (the Type object itself is M3 reflection --
//     phase 1 returns the CLSID through a byte[16] out buffer).
//   * Marshal.GetObjectForIUnknown wraps a raw IUnknown* (intptr carrier)
//     into an RCW (taking ownership -- the runtime holds the reference); the
//     reverse Marshal.GetIUnknownForObject / GetComInterfaceForObject return
//     the wrapped pointer as the intptr carrier with a reference added.
//   * Marshal.IsComObject is the RCW-descriptor check; ReleaseComObject /
//     FinalReleaseComObject release the native reference held by the RCW.
//
// CCW (COM Callable Wrapper) -- the managed-to-native direction:
//   * icall_com_ccw_create wraps a managed object behind a heap-allocated
//     native IUnknown whose vtable is generated by the runtime (7 slots:
//     QueryInterface / AddRef / Release + the IDispatch methods
//     GetTypeInfoCount / GetTypeInfo / GetIDsOfNames / Invoke, matching the
//     coreclr CCW's standard IUnknown+IDispatch vtable shape --
//     SimpleComCallWrapper m_rgpVtable[]). The CCW holds a strong GCHandle to
//     the managed object (il2cpp_gchandle.h Normal handle) so the wrapper
//     stays rooted for the native lifetime.
//   * Phase 2 QueryInterface dispatches IUnknown (identity) AND IDispatch
//     (the same single vtable carries both -- returning the same pointer is
//     legal for a single-vtable CCW) -- E_NOINTERFACE for everything else;
//     the GUID dispatch table is the documented extension path for
//     IProvideClassInfo / custom interfaces in phase 3 (coreclr's
//     SimpleComCallWrapper::QIStandardInterface). GetIDsOfNames resolves
//     names to dispIds through a per-CCW registry (first name -> dispId 1,
//     cached, case-insensitive; capacity 8, then DISP_E_UNKNOWNNAME); Invoke
//     validates the dispId and argument count and returns S_OK -- dispatching
//     into the wrapped managed method is the documented phase-3 path (M3
//     reflection wiring).
//   * Phase 4 (the ActiveX hosting surface -- the WinForms AxHost stage-3
//     dependency): the CCW is extended to a MULTI-VTABLE object. The IDispatch
//     vtable (slots 0-6) CANNOT be extended with IOleObject methods -- the
//     slot-3 layout would collide (IDispatch's GetTypeInfoCount vs
//     IOleObject's SetClientSite). coreclr's SimpleComCallWrapper instead
//     keeps a vtable PER interface; QI returns a pointer to the interface's
//     own vtable (a distinct address inside the CCW allocation -- each
//     interface's vtable pointer lives at a different offset). The CCW thus
//     implements three interface views on Windows: IUnknown+IDispatch (the
//     identity view, vtable at offset 0), IOleObject (SetClientSite /
//     DoVerb / Close -- the hosting lifecycle) and IOleClientSite
//     (GetContainer -- the container-callback surface). All views share the
//     CCW refcount, GCHandle and member registry (single-threaded contract).
//     On non-Windows the OLE views are not offered (QI returns E_NOINTERFACE
//     -- the POSIX stub; the identity IDispatch view is every-platform).
//   * Phase 5 (the event-source surface -- ActiveX control events): the CCW
//     adds IConnectionPointContainer (FindConnectionPoint / EnumConnectionPoints)
//     and IConnectionPoint (Advise / Unadvise / GetConnectionInterface /
//     GetConnectionPointContainer / EnumConnections) views on Windows. The
//     managed wiring layer declares which interface IIDs the CCW fires as
//     event sources via icall_com_ccw_register_connection_point (the
//     GetIDsOfNames dynamic-registry precedent); a native host then QIs for
//     IConnectionPointContainer, FindConnectionPoint(eventIID) and Advise(sink).
//     FindConnectionPoint hands out the per-event-interface connection point
//     view (Advise stores the QI'd sink reference, released on Unadvise or
//     CCW teardown). QI for IConnectionPoint itself is NOT answered from the
//     identity view -- the OLE contract obtains connection points exclusively
//     through FindConnectionPoint. EnumConnectionPoints / EnumConnections are
//     E_NOTIMPL in the phase-5 minimal surface (the AxHost wiring uses
//     FindConnectionPoint / Advise / Unadvise directly). On non-Windows the
//     phase-5 views are not offered (QI returns E_NOINTERFACE; the register
//     icall returns E_NOTIMPL).
//   * Phase 6 (type library evaluation -- the metadata layer): ITypeLib /
//     ITypeInfo is the COM DESCRIPTION layer (TYPEATTR / FUNCDESC -- "what
//     members, what signatures") that IDispatch::GetTypeInfoCount / GetTypeInfo
//     hand to automation hosts. The CLR's CCW re-derives it from the MANAGED
//     metadata (mscorlib reflection) at runtime. ILC records the documented
//     simplification: the CCW exposes NO ITypeInfo -- GetTypeInfoCount
//     reports 0 and GetTypeInfo returns TYPE_E_ELEMENTNOTFOUND with a null out
//     pointer (the honest "late-bound only" answer -- the runtime member
//     registry carries name -> dispId only, no signature/GUID metadata a real
//     TYPEATTR/FUNCDESC could be built from; fabricating one would present
//     false metadata). The WinForms stage-3 hosting path (AxHost/WebBrowser
//     via IOleObject/IConnectionPoint/IWebBrowser2) does NOT introspect
//     ITypeInfo -- the type library is a design-time/scripting aid, not a
//     hosting dependency. A future phase may wire ITypeInfo to the
//     Il2CppTypeInfo registry (typeinfo.h) when a consumer actually
//     introspects it.
//   * Phase 10 (IEnumVARIANT -- the per-CCW enumeration view; every platform):
//     the CCW exposes a 7-slot IEnumVARIANT view inlined at &ccw->enumView.
//     The managed wiring layer registers the enumeration items (16-byte
//     VARIANT value copies of the VT_EMPTY/VT_NULL/VT_I4/VT_R8 subset) via
//     icall_com_ccw_enum_register_item; a native host QIs for IEnumVARIANT and
//     drives Next/Skip/Reset/Clone. The identity QI dispatch for
//     kComIidIEnumVariant lives OUTSIDE the Windows gate -- the whole stage-10
//     surface is every-platform (pure memory + GUID compare, no ole32
//     dependency). Clone hands out a heap view sharing the CCW refcount with an
//     independent cursor; the RCW direction drives the same view through the
//     existing icall_com_call_vtable_slot with zero new icalls.
//   * Stage 11 (BSTR enumeration items -- WINDOWS only): the stage-10 value
//     copy cannot own a released allocation, so VT_BSTR needs a dedicated path.
//     icall_com_ccw_enum_register_bstr_item SysAllocStringLen's a copy of the
//     managed string (oleaut32 resolved at runtime like the ole32 API -- kept
//     OUT of GetOle32().ok) and the CCW OWNS it (SysFreeString'd by the CCW
//     teardown); Next hands the caller a FRESH SysAllocStringLen copy (the OLE
//     contract -- the caller VariantClear's the returned element; the stored
//     master survives). The BSTR registrations share the kCcwMaxEnumItems
//     registry with the stage-10 value items. The stage-10 every-platform
//     claim is carved out for the BSTR path: non-Windows returns E_NOTIMPL.
//   * Stage 13 (Marshal BSTR bridge -- WINDOWS only): Marshal.StringToBSTR /
//     BSTRToString / FreeBSTR map to icall_com_bstr_from_string /
//     icall_com_string_from_bstr / icall_com_bstr_free, reusing the stage-11
//     oleaut32 resolution (SysAllocStringLen / SysFreeString -- kept OUT of
//     GetOle32().ok). net48 semantics: StringToBSTR(null) -> IntPtr.Zero (0,
//     NOT ArgumentNullException); SysAllocStringLen(s->chars, s->length)
//     preserves embedded NUL units; BSTRToString(0) -> null and reads to the
//     FIRST NUL unit (PtrToStringUni semantics -- embedded NULs truncate);
//     FreeBSTR(0) -> no-op, otherwise SysFreeString. The bridge is a SEPARATE
//     path from the CCW enum ownership (stage 11) -- the two never interact.
//     Non-Windows: StringToBSTR / BSTRToString throw NotSupportedException
//     and FreeBSTR is a no-op (the null forms still follow net48 -- the null
//     checks precede the platform gate).
//
// PLATFORM CONTRACT (user iron rule #17): every COM entry point is
//   #if defined(_WIN32): full implementation (ole32 resolved at runtime via
//       LoadLibraryA/GetProcAddress -- the guid.cpp precedent; the runtime
//       library must not pull in import libs, and tests/runtime CMakeLists
//       links no ole32).
//   #else: a compilable stub that throws NotSupportedException with a
//       platform-limitation message (or returns 0 / E_NOTIMPL for the
//       HRESULT/intptr-returning forms) -- mirrors the netcore
//       Marshal.Unix.cs contract (PlatformNotSupportedException, never a
//       silent null unless the netcore contract says so). Non-Windows tests
//       assert exactly these stub behaviors (no crash, explicit error).
//
// All functions are declared on every platform (stub or not) so the headers
// are portable; com.cpp compiles the two branches under one TU.
//------------------------------------------------------------------------------

